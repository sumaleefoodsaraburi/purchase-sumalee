function parseCsvLine(line) {
  const result = [];
  let cur = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (c === '"') {
      inQuotes = !inQuotes;
    } else if (c === ',' && !inQuotes) {
      result.push(cur.trim());
      cur = '';
    } else {
      cur += c;
    }
  }
  result.push(cur.trim());
  return result;
}

function parseThaiDateIso(dateStr, timeStr) {
  if (!dateStr || dateStr.includes('รวมยอด')) return new Date().toISOString();
  const parts = dateStr.split('/');
  if (parts.length < 3) return new Date().toISOString();
  let day = parseInt(parts[0], 10);
  let month = parseInt(parts[1], 10) - 1;
  let year = parseInt(parts[2], 10);
  if (year < 100) year += 2000;

  let hours = 9;
  let minutes = 0;
  if (timeStr && timeStr.includes(':')) {
    const tParts = timeStr.split(':');
    hours = parseInt(tParts[0], 10) || 9;
    minutes = parseInt(tParts[1], 10) || 0;
  }

  const d = new Date(year, month, day, hours, minutes);
  return d.toISOString();
}

function cleanNum(val) {
  if (!val) return 0;
  const cleaned = val.replace(/,/g, '').replace(/N\/A/g, '').trim();
  return parseFloat(cleaned) || 0;
}

function extractPhone(customerName, address) {
  const text = `${customerName || ''} ${address || ''}`;
  const phoneMatch = text.match(/(0\d{1,2}[-\s]?\d{3,4}[-\s]?\d{3,4})/);
  if (phoneMatch) {
    return phoneMatch[1].replace(/\s+/g, '-');
  }
  return '-';
}

